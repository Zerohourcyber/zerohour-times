def md(text):
    """Minimal markdown -> HTML. Deliberately tiny and escape-first.

    The analysis and research text originates from a model that read untrusted
    job postings and web pages, so it is escaped BEFORE any markup is applied.
    Nothing here can emit a tag the model chose; only the handful of patterns
    below produce markup, and links are rebuilt from a strict pattern.
    """
    import re
    if not text:
        return ""
    out = []
    for raw in html.escape(text).split("\n"):
        line = raw.rstrip()
        line = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", line)
        line = re.sub(r"\[([^\]]{1,120})\]\((https?://[^\s)]{1,400})\)",
                      r'<a href="\2" target="_blank" rel="noopener noreferrer">\1</a>', line)
        line = re.sub(r"(?<!\")(?<!>)(https?://[^\s<)\"]{6,400})",
                      r'<a href="\1" target="_blank" rel="noopener noreferrer">\1</a>', line)
        if not line.strip():
            out.append("")
        elif line.startswith("#### "):
            out.append(f"<h5>{line[5:]}</h5>")
        elif line.startswith("### "):
            out.append(f"<h4>{line[4:]}</h4>")
        elif line.startswith("## "):
            out.append(f"<h3>{line[3:]}</h3>")
        elif line.lstrip().startswith(("- ", "* ", "– ")):
            out.append(f"<li>{line.lstrip()[2:]}</li>")
        elif line.startswith("|"):
            cells = [c.strip() for c in line.strip("|").split("|")]
            if all(set(c) <= set("-: ") for c in cells):
                continue
            out.append("<tr>" + "".join(f"<td>{c}</td>" for c in cells) + "</tr>")
        else:
            out.append(f"<p>{line}</p>")
    body, in_list, in_table = [], False, False
    for ln in out:
        is_li, is_tr = ln.startswith("<li>"), ln.startswith("<tr>")
        if is_li and not in_list:
            body.append("<ul>"); in_list = True
        if not is_li and in_list:
            body.append("</ul>"); in_list = False
        if is_tr and not in_table:
            body.append("<table>"); in_table = True
        if not is_tr and in_table:
            body.append("</table>"); in_table = False
        body.append(ln)
    if in_list:
        body.append("</ul>")
    if in_table:
        body.append("</table>")
    return "\n".join(body)


