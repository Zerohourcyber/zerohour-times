#!/usr/bin/env python3
"""Build the ZeroHour Job Intelligence dashboard.

A static report generated by the service that already exists: no database, no
framework, no build step, no CDN. One JSON file for the data and one
self-contained HTML file to read it, both written atomically so a failed run
can never leave a half-written dashboard behind.

Reads only our own artifacts — queue.json, assessments.jsonl, research.jsonl,
last-run.json, spend.json. It does NOT read JobSync's database: JobSync stays
the system of record and this stays a reader of work we already did, so the
dashboard cannot be broken by a JobSync upgrade and cannot corrupt it.
"""

import argparse, html, json, os, sys, tempfile
from datetime import datetime, timezone

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import match as M

QUEUE = f"{M.STATE_DIR}/queue.json"
RESEARCH = f"{M.STATE_DIR}/research.jsonl"
LAST_RUN = f"{M.STATE_DIR}/last-run.json"
EXTERNAL = f"{M.STATE_DIR}/externally-scored.json"
WWW = M.S.WWW_DIR
JOBSYNC = M.S.JOBSYNC_URL
STALE_HOURS = 30          # a stage older than this is reported as stale, not fresh


def atomic_write(path, text):
    """Write via a temp file in the same directory, then rename. A crash or a
    full disk leaves the previous dashboard intact rather than a truncated one."""
    os.makedirs(os.path.dirname(path), exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=os.path.dirname(path), prefix=".tmp-")
    try:
        with os.fdopen(fd, "w") as fh:
            fh.write(text)
        os.replace(tmp, path)
    except Exception:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise


def jsonl(path):
    out = []
    try:
        with open(path) as fh:
            for line in fh:
                try:
                    out.append(json.loads(line))
                except json.JSONDecodeError:
                    continue
    except OSError:
        pass
    return out


def load_json(path, default):
    try:
        with open(path) as fh:
            return json.load(fh)
    except (OSError, json.JSONDecodeError):
        return default


def age_hours(iso):
    if not iso:
        return None
    try:
        t = datetime.fromisoformat(iso.replace("Z", "+00:00"))
        if t.tzinfo is None:
            t = t.replace(tzinfo=timezone.utc)
        return (datetime.now(timezone.utc) - t).total_seconds() / 3600
    except ValueError:
        return None


def build(cfg):
    now = datetime.now(M.TZ)
    queue = load_json(QUEUE, {})
    last_run = load_json(LAST_RUN, {})
    spend = M.load_spend()
    assessments = jsonl(M.ASSESS_LOG)
    research_rows = jsonl(RESEARCH)

    # Latest assessment per URL; only those still in the queue count as "ours".
    latest = {}
    for r in assessments:
        if r.get("score") is None:
            continue
        prev = latest.get(r["url"])
        if not prev or r["ts"] >= prev["ts"]:
            latest[r["url"]] = r
    assessed = {u: r for u, r in latest.items() if u in queue}
    # find_job reports "scored" for anything with a match, including matches this
    # pipeline created, so subtract our own to get the ones assessed by hand.
    external_all = load_json(EXTERNAL, {})
    external = [u for u in external_all if u in queue and u not in assessed]
    awaiting = [u for u in queue if u not in assessed and u not in external_all]
    failed = [r for r in assessments if r.get("error") and r.get("url") in queue]

    research = {}
    for r in research_rows:
        if r.get("research"):
            research[r["url"]] = r

    opportunities = []
    for url, a in assessed.items():
        q = queue.get(url, {})
        opportunities.append({
            "company": a.get("company"), "title": a.get("jobTitle"),
            "url": url,
            "jobsync_url": f"{JOBSYNC}/dashboard/myjobs/{a['jobId']}" if a.get("jobId") else None,
            "verdict": a.get("verdict"), "recommendation": a.get("recommendation"),
            "score": a.get("score"),
            "desirability": a.get("desirability"), "direction": a.get("direction"),
            "location": q.get("location"), "workplace": q.get("workplaceType"),
            "source": q.get("source"),
            "job_type": q.get("jobType"),
            "downgraded": a.get("downgraded", False),
            "model": a.get("model"), "prompt_version": a.get("prompt_version"),
            "assessed_at": a.get("ts"),
            "analysis": a.get("matchText") or "",
            "research": (research.get(url) or {}).get("research"),
            "researched_at": (research.get(url) or {}).get("ts"),
        })
    order = {"apply": 0, "explore": 1, "skip": 2, None: 3}
    opportunities.sort(key=lambda o: (order.get(o["verdict"], 3), -(o["score"] or 0)))

    def stage(name, iso, ok, detail):
        a = age_hours(iso)
        return {"name": name, "last": iso, "age_hours": round(a, 1) if a is not None else None,
                "status": ("never run" if iso is None else
                           "ok" if ok and (a is not None and a <= STALE_HOURS) else
                           "stale" if ok else "failed"),
                "detail": detail}

    last_research = max((r["ts"] for r in research_rows if r.get("ts")), default=None)
    last_assess = max((r["ts"] for r in assessments if r.get("ts")), default=None)

    stages = [
        stage("Discovery", last_run.get("ran_at"), last_run.get("ok", False),
              f"{last_run.get('kept', 0)} kept of {last_run.get('fetched', 0)} fetched "
              f"across {last_run.get('companies', 0)} employers"
              + (f" · {len(last_run.get('deferred') or [])} batch(es) deferred to the next run"
                 if last_run.get("deferred") else "")),
        stage("Matching", last_assess, True,
              f"{len(assessed)} assessed by pipeline, "
              f"{len(external)} assessed in JobSync, "
              f"{len(awaiting)} awaiting"
              + (f", {len(failed)} failed" if failed else "")),
        stage("Research", last_research, True, f"{len(research)} researched"),
    ]

    return {
        "generated_at": now.isoformat(timespec="seconds"),
        "generated_human": now.strftime("%A %d %B %Y, %H:%M %Z"),
        "counts": {
            "discovered": len(queue),
            "new_today": last_run.get("created", 0),
            "assessed": len(assessed),
            "awaiting": len(awaiting),
            "researched": len(research),
            "assessed_in_jobsync": len(external),
            "apply": sum(1 for o in opportunities if o["verdict"] == "apply"),
            "explore": sum(1 for o in opportunities if o["verdict"] == "explore"),
        },
        "budget": {"spent": round(spend.get("usd", 0), 4),
                   "cap": cfg.get("matching", {}).get("max_usd_per_day", 2.0),
                   "calls": spend.get("calls", 0), "date": spend.get("date")},
        "stages": stages,
        "errors": [{"company": r.get("company"), "title": r.get("jobTitle"),
                    "error": r.get("error")} for r in failed][:20],
        "opportunities": opportunities,
        "jobsync_url": JOBSYNC,
    }


