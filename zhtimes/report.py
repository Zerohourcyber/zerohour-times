def section(text, *names):
    """Pull one named markdown section out of an analysis, for the featured ad."""
    if not text:
        return ""
    lines = text.splitlines()
    for i, ln in enumerate(lines):
        t = ln.strip().lstrip("#").strip().lower()
        if ln.strip().startswith("#") and any(t.startswith(n.lower()) for n in names):
            out = []
            for nxt in lines[i + 1:]:
                if nxt.strip().startswith("##"):
                    break
                out.append(nxt)
            return "\n".join(out).strip()
    return ""


